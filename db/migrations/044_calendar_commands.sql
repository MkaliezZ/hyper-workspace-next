-- Calendar originals remain in CalDAV. These are private product intents and observations.
CREATE TABLE cw_calendar_commands (
 id uuid PRIMARY KEY,
 workspace_id uuid NOT NULL REFERENCES cw_workspaces,
 actor_id uuid NOT NULL REFERENCES cw_users,
 identity_credential_id uuid NOT NULL REFERENCES cw_identity_credentials,
 provider_key text NOT NULL,
 source_actor_id text NOT NULL,
 calendar_id text NOT NULL,
 object_id text NOT NULL,
 source_uid text NOT NULL,
 operation text NOT NULL CHECK(operation IN ('create','update','delete')),
 idempotency_key uuid NOT NULL,
 params_hash text NOT NULL,
 plan jsonb NOT NULL,
 title text NOT NULL,
 expected_etag text,
 desired_ical text,
 desired_digest text,
 state text NOT NULL CHECK(state IN ('prepared','applying','succeeded','failed','recovery_required','cancelled')),
 stop_requested_at timestamptz,
 source_acknowledged boolean NOT NULL DEFAULT false,
 source_etag text,
 observed_result text CHECK(observed_result IN ('matched','absent')),
 error text,
 attempted_at timestamptz,
 acknowledged_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(workspace_id,actor_id,idempotency_key),
 CHECK ((operation='create' AND expected_etag IS NULL) OR (operation<>'create' AND expected_etag IS NOT NULL)),
 CHECK ((operation='delete' AND desired_ical IS NULL AND desired_digest IS NULL) OR (operation<>'delete' AND desired_ical IS NOT NULL AND desired_digest IS NOT NULL)),
 CHECK (desired_ical IS NULL OR octet_length(desired_ical)<=262144)
);
CREATE INDEX cw_calendar_commands_actor_history ON cw_calendar_commands(workspace_id,actor_id,created_at DESC,id DESC);
